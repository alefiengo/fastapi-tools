"""Real Alembic against an authorized temporary SQLite DB, not production proof."""
from pathlib import Path

from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.util.exc import AutogenerateDiffsDetected
import pytest
from sqlalchemy import Column, Integer, MetaData, String, Table, create_engine, inspect, text


def test_local_revision_check_detects_drift_and_rename_is_not_inferred(tmp_path):
    config = Config()
    config.set_main_option('script_location', str(Path(__file__).parent / 'alembic_fixture'))
    url = f'sqlite:///{tmp_path / "migration.db"}'
    config.set_main_option('sqlalchemy.url', url)
    command.upgrade(config, 'head')
    command.check(config)
    engine = create_engine(url)
    try:
        with engine.begin() as connection:
            assert connection.scalar(text('SELECT version_num FROM alembic_version')) == 'products_base'
            connection.execute(text("INSERT INTO products (id, name) VALUES (1, 'chair')"))
        # Renamed target metadata yields add/drop, not a data-preserving rename.
        renamed = MetaData()
        Table('products', renamed, Column('id', Integer, primary_key=True), Column('label', String(100)))
        with engine.connect() as connection:
            diffs = compare_metadata(MigrationContext.configure(connection), renamed)
            assert any(d[0] == 'add_column' and d[3].name == 'label' for d in diffs)
            assert any(d[0] == 'remove_column' and d[3].name == 'name' for d in diffs)
            assert connection.scalar(text('SELECT name FROM products WHERE id = 1')) == 'chair'
        with engine.begin() as connection:
            connection.execute(text('ALTER TABLE products ADD COLUMN unexpected INTEGER'))
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(config)
        assert 'unexpected' in {c['name'] for c in inspect(engine).get_columns('products')}
    finally:
        engine.dispose()
